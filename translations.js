/* ---------- Language switch (no need to edit below) ---------- */
(function () {
    const langBtn = document.getElementById('lang-toggle');
    const englishTitle = document.title;
    const textNodes = [];
    const customBlocks = [];

    // Remember every piece of text in its original English
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        if (node.parentElement.closest('script, [data-fr]')) continue;
        const key = node.nodeValue.replace(/\s+/g, ' ').trim();
        if (!frenchText[key]) continue;
        const english = node.nodeValue;
        textNodes.push({
            node,
            english,
            // keep the spaces around the text, e.g. "Hi, it's " before <span>Aya</span>
            french: english.match(/^\s*/)[0] + frenchText[key] + english.match(/\s*$/)[0]
        });
    }

    // Elements whose whole French version is written in a data-fr attribute
    document.querySelectorAll('[data-fr]').forEach(el => {
        customBlocks.push({ el, english: el.innerHTML });
    });

    function setLanguage(lang) {
        const fr = lang === 'fr';
        textNodes.forEach(t => {
            t.node.nodeValue = fr ? t.french : t.english;
        });
        customBlocks.forEach(b => {
            b.el.innerHTML = fr ? b.el.dataset.fr : b.english;
        });
        document.documentElement.lang = lang;
        document.title = fr ? 'Mon portfolio' : englishTitle;
        langBtn.textContent = fr ? 'EN' : 'FR';
        langBtn.setAttribute('aria-label', fr ? 'Switch to English' : 'Passer en français');
        try { localStorage.setItem('lang', lang); } catch (e) {}
    }

    langBtn.addEventListener('click', () => {
        setLanguage(document.documentElement.lang === 'fr' ? 'en' : 'fr');
    });

    let saved = null;
    try { saved = localStorage.getItem('lang'); } catch (e) {}
    if (saved === 'fr') setLanguage('fr');
})();
